// Design-session capture: Joss's Marksman offer, taking it, the career page and the board.
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
const repo = new URL('..', import.meta.url).pathname;
const out = join(repo, 'docs/screenshots/2026-10-28-specialisations');
mkdirSync(out, { recursive: true });
const port = 5900;
const server = spawn(join(repo, 'node_modules/.bin/vite'), ['--port', String(port), '--strictPort'], { cwd: repo, stdio: 'pipe' });
await new Promise((ok) => server.stdout.on('data', (d) => { if (String(d).includes('Local')) ok(); }));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
page.on('pageerror', (e) => console.error('page error', e.message));
await page.addInitScript(() => { let s = 20261023; Math.random = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 2 ** 32; }; });
let n = 0;
const shot = async (name) => { await page.waitForTimeout(300); await page.screenshot({ path: join(out, `${String(++n).padStart(2, '0')}-${name}.png`) }); };
const click = async (sel) => { const el = page.locator(sel).filter({ visible: true }).first(); if (!(await el.count())) return false; await el.scrollIntoViewIfNeeded(); await el.click(); await page.waitForTimeout(200); return true; };
try {
  await page.goto(`http://localhost:${port}/`);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForSelector('#app *');
  await click('[data-action="difficulty"]');
  await page.evaluate(() => {
    const key = Object.keys(localStorage).find((k) => /^syndicate-slot-\d+$/.test(k));
    const s = JSON.parse(localStorage.getItem(key));
    const op = s.crew.find((o) => o.role === 'muscle');
    Object.assign(op.stats, { combat: Math.max(op.stats.combat, 11), cool: Math.max(op.stats.cool, 9) });
    op.track = { ...(op.track ?? {}), overwatch: { rifle: 3 } };
    op.gear.weapon = { uid: 'g90', type: 'rifle', tier: 'street' };
    localStorage.setItem(key, JSON.stringify(s));
  });
  await page.reload();
  await page.waitForSelector('#app *');
  await click('[data-action="continue"]');
  await page.waitForTimeout(1500);
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot('today-with-offer');
  await click('[data-action="open-message"]:has-text("could train")');
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot('marksman-offer');
  await click('[data-action="decide"][data-option="marksman"]');
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot('offer-taken');
  await click('[data-action="nav"][data-id="crew"]');
  await click('[data-action="open-op"]:has-text("muscle")');
  await page.evaluate(() => window.scrollTo(0, 0));
  await shot('career-page');
  await click('[data-action="nav"][data-id="jobs"]');
  await click('[data-action="open-job"]');
  await click('[data-action="joss"]');
  await click('[data-action="pick-slot"][data-id="over"]');
  await shot('overwatch-picker');
  await click('.sheet [data-action="assign"]:not([disabled])');
  await page.evaluate(() => document.querySelector('.board')?.scrollIntoView({ block: 'center' }));
  await shot('board-with-marksman');
} finally { await browser.close(); server.kill(); }
console.log('done', n);
