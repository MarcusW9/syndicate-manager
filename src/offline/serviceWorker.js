// Offline play (DESIGN.md, 2026-10-29). The build (vite.config.js) writes this service worker
// out as sw.js with the list of every file it built. On the first visit the browser stores a copy
// of all of them; after that the game opens from that copy, online or not, and checks for a newer
// version in the background. Saves are untouched: they live in the browser's own storage
// (src/save/save.js), not in this cache.
//
// Plain code as a string: it runs in the service worker, not the page, so it can't import anything.

/** The service worker's source, for this build's files. version names the cache, so a new build replaces the old copy. */
export function serviceWorkerSource(files, version) {
  return `// Generated by vite.config.js from src/offline/serviceWorker.js. Do not edit.
const CACHE = ${JSON.stringify(`game-${version}`)};
const FILES = ${JSON.stringify(files)};

// Store a copy of every file, then take over straight away.
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

// Drop copies of older versions.
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('game-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

// Serve from the stored copy; opening the game (a page load) always gets the stored index.html.
// Anything not stored goes to the network as usual.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  const key = req.mode === 'navigate' ? new URL('./index.html', self.registration.scope).href : req;
  event.respondWith(caches.open(CACHE).then((c) => c.match(key, { ignoreSearch: req.mode === 'navigate', ignoreVary: true }))
    .then((hit) => hit ?? fetch(req)));
});
`;
}
